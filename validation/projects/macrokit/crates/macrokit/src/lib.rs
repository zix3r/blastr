//! Typed, unit-aware configuration settings driven by hand-written macros.
//!
//! `macrokit` is the configuration layer of a small process controller: it
//! knows about physical [dimensions](dimension::Dimension) and [units](unit::Unit),
//! parses operator supplied text into typed [settings](value::SettingValue),
//! keeps an [engine](engine::Engine) of effective values with provenance, and
//! exposes a tiny [command registry](commands::Registry) on top of it.
//!
//! Three macros keep the boilerplate small:
//!
//! * `#[derive(Describe)]` (from `macrokit-derive`) reflects over struct fields,
//! * `#[command]` (from `macrokit-derive`) registers a handler function,
//! * [`ensure!`], [`newtype_ids!`] and [`command_table!`] are `macro_rules!`
//!   helpers exported by this crate.
//!
//! The unit, schema and rule tables are generated by `build.rs` from the data
//! files in `data/` and included from `$OUT_DIR`.

